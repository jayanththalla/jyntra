export type IconProps = Omit<React.ComponentProps<typeof HugeiconsIcon>, "icon">;
export type IconComponent = (props: IconProps) => React.JSX.Element;

function make(icon: HugeIcon): IconComponent {
  return function AppIcon({ size = 16, strokeWidth = 1.8, ...props }: IconProps) {
    return <HugeiconsIcon icon={icon} size={size} strokeWidth={strokeWidth} aria-hidden="true" {...props} />;
  };
}

