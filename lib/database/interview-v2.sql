-- Scoring. interview_answers.score was ALREADY constrained to 0..100, so old rows are not rescaled. They were produced by an
-- unweighted, model-judged rubric, so they are marked 'legacy' (the DEFAULT) and new rows carry 'v2' plus the validated per-dimension
-- breakdown. Reports label legacy rows instead of mixing them silently with weighted ones.
ALTER TABLE interview_answers ADD COLUMN IF NOT EXISTS rubric_version TEXT NOT NULL DEFAULT 'legacy';   -- 'legacy' | 'v2'
ALTER TABLE interview_answers ADD COLUMN IF NOT EXISTS rubric_kind    TEXT;                              -- technical | behavioural | communication
ALTER TABLE interview_answers ADD COLUMN IF NOT EXISTS rubric         JSONB;                             -- {components:[{name,weight,score,evidence}], communication:{...}}
ALTER TABLE interview_answers ADD COLUMN IF NOT EXISTS input_mode     TEXT;                              -- voice | realtime | text (how the answer arrived)
ALTER TABLE interview_answers ADD COLUMN IF NOT EXISTS transcript_edited BOOLEAN NOT NULL DEFAULT false;

-- Sessions: pause/resume and formal-interview timing. 'paused' needs the status CHECK widened (constraint is replaced, rows untouched).
DO $$
DECLARE c TEXT;
BEGIN
  FOR c IN SELECT conname FROM pg_constraint WHERE conrelid = 'interview_sessions'::regclass AND contype = 'c' AND pg_get_constraintdef(oid) ILIKE '%status%' LOOP
    EXECUTE format('ALTER TABLE interview_sessions DROP CONSTRAINT %I', c);
  END LOOP;
  ALTER TABLE interview_sessions ADD CONSTRAINT interview_sessions_status_check CHECK (status IN ('active','paused','completed','abandoned'));
END $$;
ALTER TABLE interview_sessions ADD COLUMN IF NOT EXISTS target_minutes   INT;            -- formal: 10 | 20 | 30
ALTER TABLE interview_sessions ADD COLUMN IF NOT EXISTS elapsed_seconds  INT NOT NULL DEFAULT 0;
ALTER TABLE interview_sessions ADD COLUMN IF NOT EXISTS paused_at        TIMESTAMPTZ;
ALTER TABLE interview_sessions ADD COLUMN IF NOT EXISTS stage            TEXT NOT NULL DEFAULT 'spoken';   -- spoken | written | done
ALTER TABLE interview_sessions ADD COLUMN IF NOT EXISTS resume_profile_id INT;
ALTER TABLE interview_sessions ADD COLUMN IF NOT EXISTS english         JSONB;         -- spoken-English assessment, computed at completion
ALTER TABLE interview_sessions ADD COLUMN IF NOT EXISTS written_result   JSONB;
ALTER TABLE interview_sessions ADD COLUMN IF NOT EXISTS report_version   INT NOT NULL DEFAULT 1;   -- 1 = original report shape, 2 = rubric report
ALTER TABLE interview_sessions ADD COLUMN IF NOT EXISTS pdf_generated_at TIMESTAMPTZ;   -- metadata only: the PDF is rendered on demand from the saved report

-- Resume profile for interviews. The uploaded FILE is never stored (parsed in memory and dropped); only the structured profile the
-- user reviewed is kept, scoped to the owner.
CREATE TABLE IF NOT EXISTS interview_resume_profiles (
  id          SERIAL PRIMARY KEY,
  user_id     INT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  profile     JSONB NOT NULL,
  source      TEXT NOT NULL DEFAULT 'upload',       -- upload | atlas | manual
  confirmed   BOOLEAN NOT NULL DEFAULT false,       -- the user inspected and accepted/corrected it
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS interview_resume_profiles_user_idx ON interview_resume_profiles (user_id, updated_at DESC);

-- Written tests (MCQ / multi-select / true-false / short explanation / SQL). Questions generated by AI are stored with their source;
-- the bank itself ships in code. Correct answers stay on the server until the attempt is submitted.
CREATE TABLE IF NOT EXISTS written_test_questions (
  id          TEXT PRIMARY KEY,                      -- stable id (bank id, or 'ai:<hash>')
  source      TEXT NOT NULL CHECK (source IN ('bank','ai')),
  category    TEXT NOT NULL,
  kind        TEXT NOT NULL,
  difficulty  TEXT NOT NULL,
  definition  JSONB NOT NULL,                        -- validated question incl. answer + explanation
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS written_test_attempts (
  id          SERIAL PRIMARY KEY,
  user_id     INT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  session_id  INT REFERENCES interview_sessions(id) ON DELETE CASCADE,
  question_id TEXT NOT NULL,
  category    TEXT NOT NULL,
  response    JSONB NOT NULL,
  correct     BOOLEAN,
  score       INT CHECK (score BETWEEN 0 AND 100),
  detail      JSONB,                                  -- SQL: passed/failed cases, expected vs actual, execution mode
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS written_test_attempts_user_idx ON written_test_attempts (user_id, created_at DESC);

-- Funding connector run history (scheduled ingestion + source health across all connectors).
CREATE TABLE IF NOT EXISTS funding_connector_runs (
  id            SERIAL PRIMARY KEY,
  connector     TEXT NOT NULL,
  started_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
  finished_at   TIMESTAMPTZ,
  ok            BOOLEAN,
  fetched       INT NOT NULL DEFAULT 0,
  stored        INT NOT NULL DEFAULT 0,
  error_category TEXT,
  note          TEXT
);
CREATE INDEX IF NOT EXISTS funding_connector_runs_idx ON funding_connector_runs (connector, started_at DESC);

-- Official links per company, with where each came from. A field is only ever set from evidence we recorded.
CREATE TABLE IF NOT EXISTS company_link_checks (
  company_key        TEXT PRIMARY KEY,               -- normalised company name
  company_name       TEXT NOT NULL,
  website_url        TEXT,
  linkedin_url       TEXT,
  careers_url        TEXT,
  verification_status TEXT NOT NULL DEFAULT 'unverified' CHECK (verification_status IN ('verified','partially_verified','unverified')),
  sources            JSONB NOT NULL DEFAULT '[]',    -- [{field,url,evidence}]
  last_verified_at   TIMESTAMPTZ,
  last_attempt_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
  attempt_note       TEXT
);
ALTER TABLE funding_articles ADD COLUMN IF NOT EXISTS source_connector TEXT;       -- which connector produced the row (rss | official | tavily | ...)
ALTER TABLE funding_articles ADD COLUMN IF NOT EXISTS verification_status TEXT;    -- official | press | single_source | NULL

-- Wall-clock accounting for pause/resume: time counts only while a session is active.
ALTER TABLE interview_sessions ADD COLUMN IF NOT EXISTS active_since TIMESTAMPTZ NOT NULL DEFAULT now();

